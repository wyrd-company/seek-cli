#!/usr/bin/env bun
/**
 * Generates seek's published reference under docs/user/reference/ from the
 * authoritative definitions, as docs/technical-designs/documentation.yml
 * describes: the command line from createProgram() and EXIT_STATUSES, and the
 * HTTP API, configuration and research job envelope from their definitions in
 * docs/specifications/, which it also copies byte for byte.
 *
 *   bun run docs:reference          write the reference
 *   generateReference()             the files, by path under docs/user/reference/
 */
import { readFileSync, rmSync, mkdirSync, writeFileSync } from "node:fs";
import { dirname, join, relative } from "node:path";
import type { Argument, Command, Option } from "commander";
import { createProgram } from "../../src/program.ts";
import { EXIT_STATUSES } from "../../src/lib/exit-status.ts";
import { cell, code, prose, table } from "./markdown.ts";
import { DEFINITIONS, filesUnder, REFERENCE_DIR, ROOT, SPECIFICATIONS_DIR as SPECIFICATIONS } from "./paths.ts";

const GENERATED = "<!-- Generated by `bun run docs:reference` from seek's definitions. Do not edit. -->";

/** Front matter order of the generated pages; nav decides their places, these keep a stable fallback. */
const ORDER = { commands: 100, configuration: 140, httpApi: 150, researchJobEnvelope: 160 };

/** A page: front matter, then each non-empty block separated by a blank line. */
function page(title: string, order: number, blocks: string[]): string {
  const frontMatter = ["---", `title: ${title}`, "product: seek", `order: ${order}`, "---"].join("\n");
  return [frontMatter, GENERATED, ...blocks.map((b) => b.trim()).filter(Boolean)].join("\n\n") + "\n";
}

function fence(language: string, content: string): string {
  return ["```" + language, content.trimEnd(), "```"].join("\n");
}

// ---------- Command line ----------

export interface CommandEntry {
  path: string[];
  command: Command;
}

/** Every command of the tree, depth first in declaration order, the root first. */
export function commandTree(program: Command): CommandEntry[] {
  const walk = (command: Command, path: string[]): CommandEntry[] => [
    { path, command },
    ...command.commands.flatMap((child) => walk(child, [...path, child.name()])),
  ];
  return walk(program, [program.name()]);
}

/** The page file of a command: its path joined with hyphens. */
export function commandFile(path: string[]): string {
  return `commands/${path.join("-")}.md`;
}

/** Builds the program with the built-in defaults, whatever the environment that runs the generator sets. */
export function programWithBuiltInDefaults(): Command {
  const saved = { host: process.env.SEEK_SERVER_HOST, port: process.env.SEEK_SERVER_PORT };
  delete process.env.SEEK_SERVER_HOST;
  delete process.env.SEEK_SERVER_PORT;
  try {
    return createProgram();
  } finally {
    if (saved.host !== undefined) process.env.SEEK_SERVER_HOST = saved.host;
    if (saved.port !== undefined) process.env.SEEK_SERVER_PORT = saved.port;
  }
}

/** Full help as `seek <path> --help` prints it to a pipe: 80 columns, no colour. */
export function renderHelp(command: Command): string {
  let help = "";
  command.configureOutput({
    getOutHelpWidth: () => 80,
    getOutHasColors: () => false,
    writeOut: (text) => (help += text),
  });
  command.outputHelp();
  return help;
}

/** The default `--help` shows for an option, or undefined when it shows none. */
function optionDefault(option: Option): string | undefined {
  if (option.defaultValue === undefined) return undefined;
  const shown = option.required || option.optional || (option.isBoolean() && typeof option.defaultValue === "boolean");
  if (!shown) return undefined;
  return option.defaultValueDescription || JSON.stringify(option.defaultValue);
}

function argumentRow(argument: Argument): string[] {
  const name = argument.name() + (argument.variadic ? "..." : "");
  const required = argument.required ? (argument.variadic ? "Yes, one or more" : "Yes") : argument.variadic ? "No, any number" : "No";
  const value = argument.defaultValue === undefined ? "" : code(JSON.stringify(argument.defaultValue));
  return [code(name), required, cell(argument.description ?? ""), value];
}

function commandPage(entry: CommandEntry, entries: CommandEntry[], order: number): string {
  const { command, path } = entry;
  const help = command.createHelp();
  const title = path.join(" ");
  const body: string[] = [prose(help.commandDescription(command) || command.description())];

  if (path.length > 1) {
    const parent = entries.find((e) => e.command === command.parent)!;
    body.push(`Part of ${linkTo(parent, entry)}.`);
  }

  body.push("## Usage", fence("text", commandUsageLine(command)));

  const args = help.visibleArguments(command);
  if (args.length > 0) {
    body.push("## Arguments", table(["Argument", "Required", "Description", "Default"], args.map(argumentRow)));
  }

  const options = help.visibleOptions(command);
  body.push(
    "## Options",
    table(
      ["Option", "Description", "Default"],
      options.map((option) => {
        const shown = optionDefault(option);
        const extra = [
          option.argChoices ? `Choices: ${option.argChoices.map((c) => code(c)).join(", ")}.` : "",
          option.envVar ? `Environment: ${code(option.envVar)}.` : "",
          option.mandatory ? "Required." : "",
        ].filter(Boolean);
        return [code(help.optionTerm(option)), [cell(option.description ?? ""), ...extra].filter(Boolean).join(" "), shown === undefined ? "" : code(shown)];
      }),
    ),
  );

  const children = entries.filter((e) => e.command.parent === command);
  if (children.length > 0) {
    body.push(
      "## Commands",
      table(["Command", "Description"], children.map((child) => [linkTo(child, entry), cell(child.command.description())])),
    );
  }

  if (path.length === 1) {
    body.push(
      "## Exit statuses",
      "Every command exits with one of these statuses.",
      table(["Code", "Name", "Meaning"], EXIT_STATUSES.map((s) => [code(String(s.code)), code(s.name), cell(s.meaning)])),
    );
  } else {
    const root = entries[0]!;
    const href = relative(dirname(commandFile(path)), commandFile(root.path));
    body.push("## Exit statuses", `${code(title)} exits with one of the [exit statuses of ${code(root.path.join(" "))}](${href}#exit-statuses).`);
  }

  body.push("## Help", `The output of ${code(`${title} --help`)}:`, fence("text", renderHelp(command)));
  return page(title, order, body);
}

/** `seek web exa [options] <query...>`: the usage line with the full command path. */
function commandUsageLine(command: Command): string {
  const names: string[] = [];
  for (let c: Command | null = command; c; c = c.parent) names.unshift(c.name());
  return `${names.join(" ")} ${command.usage()}`.trim();
}

function linkTo(target: CommandEntry, from: CommandEntry): string {
  const href = relative(dirname(commandFile(from.path)), commandFile(target.path)) || commandFile(target.path).split("/").pop()!;
  return `[${code(target.path.join(" "))}](${href})`;
}

function commandPages(): Map<string, string> {
  const program = programWithBuiltInDefaults();
  const entries = commandTree(program);
  const files = new Map<string, string>();
  entries.forEach((entry, index) => files.set(commandFile(entry.path), commandPage(entry, entries, ORDER.commands + index)));
  return files;
}

// ---------- JSON Schema ----------

type Schema = Record<string, any>;

function typeOf(schema: Schema): string {
  if (schema.const !== undefined) return schema.type ?? typeof schema.const;
  if (Array.isArray(schema.type)) return schema.type.join(" or ");
  if (schema.type === "array" && schema.items) return `array of ${typeOf(schema.items)}`;
  if (schema.type) return schema.type + (schema.format ? ` (${schema.format})` : "");
  if (schema.oneOf?.every((s: Schema) => typeof s.const === "string")) return "string";
  return "any";
}

function accepted(schema: Schema): string {
  if (schema.enum) return schema.enum.map((v: unknown) => code(String(v))).join(", ");
  if (schema.oneOf && schema.oneOf.every((s: Schema) => s.const !== undefined)) {
    return schema.oneOf.map((s: Schema) => code(String(s.const))).join(", ");
  }
  if (schema.pattern) return `Matches ${code(schema.pattern)}`;
  if (schema.format === "uri") return "A URI";
  if (schema.const !== undefined) return code(JSON.stringify(schema.const));
  return "";
}

function settingsTable(schema: Schema): string {
  const rows = Object.entries(schema.properties as Record<string, Schema>).map(([name, property]) => [
    code(name),
    typeOf(property),
    accepted(property),
    property.default === undefined ? "" : code(String(property.default)),
    (property.examples ?? []).map((e: unknown) => code(String(e))).join(", "),
    cell(property.description ?? ""),
  ]);
  return table(["Key", "Type", "Accepted values", "Default", "Example", "Description"], rows);
}

function configurationPage(): string {
  const file = readJson(DEFINITIONS.configurationFile);
  const environment = readJson(DEFINITIONS.configurationEnvironment);
  const other = (schema: Schema) =>
    schema.additionalProperties && typeof schema.additionalProperties === "object" && schema.additionalProperties.description
      ? `Other keys: ${prose(schema.additionalProperties.description)}`
      : schema.additionalProperties === false
        ? "Other keys are rejected."
        : "";
  return page("Configuration reference", ORDER.configuration, [
    "The settings seek reads from its configuration file and from its environment, generated from their JSON Schema definitions.",
    `## ${prose(file.title)}`,
    prose(file.description),
    `Definition: [${DEFINITIONS.configurationFile}](${DEFINITIONS.configurationFile}) (JSON Schema 2020-12). Type: ${file.type}.`,
    settingsTable(file),
    other(file),
    `## ${prose(environment.title)}`,
    prose(environment.description),
    `Definition: [${DEFINITIONS.configurationEnvironment}](${DEFINITIONS.configurationEnvironment}) (JSON Schema 2020-12). Type: ${environment.type}; every value is a string.`,
    settingsTable(environment),
    other(environment),
  ]);
}

/** Field rows of an object schema, nested objects as dotted paths. */
function fieldRows(schema: Schema, prefix = ""): string[][] {
  const required = new Set<string>(schema.required ?? []);
  return Object.entries((schema.properties ?? {}) as Record<string, Schema>).flatMap(([name, property]) => {
    const path = prefix + name;
    const row = [code(path), typeOf(property), accepted(property), required.has(name) ? "Yes" : "No", cell(property.description ?? "")];
    const nested = property.type === "object" && property.properties ? fieldRows(property, `${path}.`) : [];
    return [row, ...nested];
  });
}

function constraintLines(schema: Schema): string[] {
  const lines: string[] = [];
  for (const rule of schema.allOf ?? []) {
    const [field, condition] = Object.entries(rule.if?.properties ?? {})[0] ?? [];
    const [thenField, thenSchema] = Object.entries(rule.then?.properties ?? {})[0] ?? [];
    const [, elseSchema] = Object.entries(rule.else?.properties ?? {})[0] ?? [];
    if (!field || !thenField) continue;
    const values = ((condition as Schema).enum ?? []).map((v: unknown) => code(String(v))).join(", ");
    lines.push(
      `- ${code(thenField)} is ${code(JSON.stringify((thenSchema as Schema).const))} when ${code(field)} is one of ${values}` +
        (elseSchema ? `, and ${code(JSON.stringify((elseSchema as Schema).const))} otherwise.` : "."),
    );
  }
  for (const [field, needs] of Object.entries((schema.dependentRequired ?? {}) as Record<string, string[]>)) {
    lines.push(`- ${code(field)} is present only with ${needs.map((n) => code(n)).join(" and ")}.`);
  }
  for (const [field, dependent] of Object.entries((schema.dependentSchemas ?? {}) as Record<string, Schema>)) {
    for (const [path, value] of constPaths(dependent)) {
      lines.push(`- With ${code(field)}, ${code(path)} is ${code(JSON.stringify(value))}.`);
    }
  }
  return lines;
}

function constPaths(schema: Schema, prefix = ""): Array<[string, unknown]> {
  if (schema.const !== undefined) return [[prefix, schema.const]];
  return Object.entries((schema.properties ?? {}) as Record<string, Schema>).flatMap(([name, property]) =>
    constPaths(property, prefix ? `${prefix}.${name}` : name),
  );
}

function researchJobEnvelopePage(): string {
  const schema = readJson(DEFINITIONS.researchJobEnvelope);
  const terminal = new Set<string>(
    (schema.allOf ?? []).flatMap((rule: Schema) => rule.if?.properties?.status?.enum ?? []),
  );
  const statuses = (schema.properties.status.oneOf as Schema[]).map((s) => [
    code(s.const),
    terminal.has(s.const) ? "Yes" : "No",
    cell(s.description ?? ""),
  ]);
  return page("Research job envelope reference", ORDER.researchJobEnvelope, [
    prose(schema.description),
    `Definition: [${DEFINITIONS.researchJobEnvelope}](${DEFINITIONS.researchJobEnvelope}) (JSON Schema 2020-12).`,
    "## Fields",
    table(["Field", "Type", "Accepted values", "Required", "Description"], fieldRows(schema)),
    schema.additionalProperties === false ? "Other fields are rejected." : "",
    "## Normalized statuses",
    prose(schema.properties.status.description),
    table(["Status", "Terminal", "Meaning"], statuses),
    "## Rules",
    constraintLines(schema).join("\n"),
  ]);
}

// ---------- OpenAPI ----------

function resolveRef(document: Schema, value: Schema): Schema {
  let current = value;
  const seen = new Set<string>();
  while (current && typeof current.$ref === "string") {
    if (seen.has(current.$ref)) throw new Error(`circular $ref ${current.$ref}`);
    seen.add(current.$ref);
    if (!current.$ref.startsWith("#/")) throw new Error(`unsupported $ref ${current.$ref}`);
    const target = current.$ref
      .slice(2)
      .split("/")
      .map((p: string) => p.replaceAll("~1", "/").replaceAll("~0", "~"))
      .reduce((node: any, key: string) => node?.[key], document);
    if (target === undefined) throw new Error(`unresolved $ref ${current.$ref}`);
    current = target;
  }
  return current;
}

function refName(value: Schema | undefined): string | undefined {
  return typeof value?.$ref === "string" ? value.$ref.split("/").pop() : undefined;
}

/** The heading of a component, so that its anchor differs from a tag's: `Health` schema, `Unauthorized` response. */
function componentHeading(name: string, kind: "schema" | "response"): string {
  return `${code(name)} ${kind}`;
}

function componentLink(name: string, kind: "schema" | "response"): string {
  return `[${code(name)}](#${anchor(`${name} ${kind}`)})`;
}

function schemaLabel(document: Schema, schema: Schema | undefined): string {
  if (!schema) return "";
  const name = refName(schema);
  if (name) return componentLink(name, "schema");
  const resolved = resolveRef(document, schema);
  return typeOf(resolved);
}

/** github-slugger's anchor for a plain heading. */
function anchor(text: string): string {
  return text.toLowerCase().replace(/[^\p{L}\p{M}\p{N}\p{Pc} -]/gu, "").replace(/ /g, "-");
}

const METHODS = ["get", "put", "post", "delete", "options", "head", "patch", "trace"] as const;

function operationSection(document: Schema, path: string, method: string, operation: Schema): string[] {
  const out: string[] = [`### ${code(`${method.toUpperCase()} ${path}`)}`];
  out.push(`**${prose(operation.summary ?? "")}**`, prose(operation.description ?? ""));
  const security = operation.security ?? document.security ?? [];
  const schemes = security.flatMap((s: Schema) => Object.keys(s));
  out.push(
    `Operation ID: ${code(operation.operationId)}. Authentication: ${schemes.length > 0 ? schemes.map((s: string) => `[${code(s)}](#${anchor(s)})`).join(", ") : "none"}.`,
  );

  const parameters = (operation.parameters ?? []).map((p: Schema) => resolveRef(document, p));
  if (parameters.length > 0) {
    out.push(
      "Parameters:",
      table(
        ["Name", "In", "Required", "Type", "Description"],
        parameters.map((p: Schema) => [code(p.name), p.in, p.required ? "Yes" : "No", typeOf(resolveRef(document, p.schema ?? {})), cell(p.description ?? "")]),
      ),
    );
  }

  if (operation.requestBody) {
    const body = resolveRef(document, operation.requestBody);
    out.push(
      `Request body (${body.required ? "required" : "optional"}): ${prose(body.description ?? "")}`,
      table(
        ["Content type", "Schema"],
        Object.entries((body.content ?? {}) as Record<string, Schema>).map(([type, media]) => [code(type), schemaLabel(document, media.schema)]),
      ),
    );
  }

  const responses = Object.entries((operation.responses ?? {}) as Record<string, Schema>);
  out.push(
    "Responses:",
    table(
      ["Status", "Description", "Content type", "Schema"],
      responses.flatMap(([status, value]) => {
        const response = resolveRef(document, value);
        const content = Object.entries((response.content ?? {}) as Record<string, Schema>);
        const name = refName(value);
        const description = name ? `${cell(response.description ?? "")} See ${componentLink(name, "response")}.` : cell(response.description ?? "");
        if (content.length === 0) return [[code(status), description, "", ""]];
        return content.map(([type, media], index) => [
          index === 0 ? code(status) : "",
          index === 0 ? description : "",
          code(type),
          schemaLabel(document, media.schema),
        ]);
      }),
    ),
  );

  // A shared response shows its examples once, under Components.
  for (const [status, value] of responses) {
    if (refName(value)) continue;
    out.push(...examples(value, `Example ${code(status)} response`));
  }
  return out;
}

function examples(response: Schema, label: string): string[] {
  return Object.entries((response.content ?? {}) as Record<string, Schema>)
    .filter(([, media]) => media.example !== undefined)
    .flatMap(([type, media]) => [`${label} (${code(type)}):`, fence("json", JSON.stringify(media.example, null, 2))]);
}

function httpApiPage(): string {
  const document = Bun.YAML.parse(readSpecification(DEFINITIONS.httpApi)) as Schema;
  const body: string[] = [
    `**${prose(document.info.summary ?? document.info.title)}**`,
    ...String(document.info.description ?? "")
      .split(/\n\s*\n/)
      .map((paragraph) => prose(paragraph.replace(/\s*\n\s*/g, " "))),
    `Definition: [${DEFINITIONS.httpApi}](${DEFINITIONS.httpApi}) (OpenAPI ${document.openapi}, API version ${code(String(document.info.version))}).`,
    "## Servers",
    table(["URL", "Description"], (document.servers ?? []).map((s: Schema) => [code(s.url), cell(s.description ?? "")])),
    "## Authentication",
  ];
  for (const [name, scheme] of Object.entries((document.components?.securitySchemes ?? {}) as Record<string, Schema>)) {
    body.push(`### ${name}`, `Type: ${code(scheme.type)}${scheme.scheme ? `, scheme ${code(scheme.scheme)}` : ""}.`, prose(scheme.description ?? ""));
  }

  const operations: Array<{ path: string; method: string; operation: Schema }> = [];
  for (const [path, item] of Object.entries((document.paths ?? {}) as Record<string, Schema>)) {
    for (const method of METHODS) if (item[method]) operations.push({ path, method, operation: item[method] });
  }
  for (const tag of (document.tags ?? []) as Schema[]) {
    body.push(`## ${tag.name}`, prose(tag.description ?? ""));
    for (const { path, method, operation } of operations.filter((o) => (o.operation.tags ?? [])[0] === tag.name)) {
      body.push(...operationSection(document, path, method, operation));
    }
  }
  const untagged = operations.filter((o) => !(o.operation.tags ?? []).length);
  if (untagged.length > 0) throw new Error(`operations without a tag: ${untagged.map((o) => o.operation.operationId).join(", ")}`);

  body.push("## Components");
  const components = document.components ?? {};
  for (const [name, schema] of Object.entries((components.schemas ?? {}) as Record<string, Schema>)) {
    body.push(`### ${componentHeading(name, "schema")}`, prose(schema.description ?? ""), `Type: ${typeOf(schema)}.`);
    if (schema.properties) body.push(table(["Field", "Type", "Accepted values", "Required", "Description"], fieldRows(schema)));
  }
  for (const [name, response] of Object.entries((components.responses ?? {}) as Record<string, Schema>)) {
    const headers = Object.entries((response.headers ?? {}) as Record<string, Schema>).map(([header, value]) => {
      const resolved = resolveRef(document, value);
      return [code(header), typeOf(resolveRef(document, resolved.schema ?? {})), accepted(resolveRef(document, resolved.schema ?? {})), cell(resolved.description ?? "")];
    });
    body.push(`### ${componentHeading(name, "response")}`, prose(response.description ?? ""));
    if (headers.length > 0) body.push(table(["Header", "Type", "Accepted values", "Description"], headers));
    const content = Object.entries((response.content ?? {}) as Record<string, Schema>);
    if (content.length > 0) {
      body.push(table(["Content type", "Schema"], content.map(([type, media]) => [code(type), schemaLabel(document, media.schema)])));
    }
    body.push(...examples(response, "Example"));
  }
  return page("HTTP API reference", ORDER.httpApi, body);
}

// ---------- Files ----------

function readSpecification(name: string): string {
  return readFileSync(join(ROOT, SPECIFICATIONS, name), "utf8");
}

function readJson(name: string): Schema {
  return JSON.parse(readSpecification(name)) as Schema;
}

/** Every generated file, by path under docs/user/reference/, with its exact bytes. */
export function generateReference(): Map<string, Uint8Array> {
  const encoder = new TextEncoder();
  const files = new Map<string, Uint8Array>();
  for (const [path, text] of commandPages()) files.set(path, encoder.encode(text));
  files.set("configuration.md", encoder.encode(configurationPage()));
  files.set("research-job-envelope.md", encoder.encode(researchJobEnvelopePage()));
  files.set("http-api.md", encoder.encode(httpApiPage()));
  for (const name of Object.values(DEFINITIONS)) {
    files.set(name, new Uint8Array(readFileSync(join(ROOT, SPECIFICATIONS, name))));
  }
  return new Map([...files].sort(([a], [b]) => a.localeCompare(b)));
}

/** Writes the reference into `dir`, removing files the generator no longer writes. */
export function writeReference(dir = join(ROOT, REFERENCE_DIR)): string[] {
  const files = generateReference();
  for (const existing of filesUnder(dir)) if (!files.has(existing)) rmSync(join(dir, existing));
  for (const [path, bytes] of files) {
    mkdirSync(dirname(join(dir, path)), { recursive: true });
    writeFileSync(join(dir, path), bytes);
  }
  return [...files.keys()];
}

if (import.meta.main) {
  const written = writeReference();
  process.stdout.write(`docs:reference wrote ${written.length} files to ${REFERENCE_DIR}\n`);
}
